import 'dart:io';

import 'src/pack_files.dart';

/// Path of the generated index, relative to the repository root.
const bundlePath = 'lib/src/bundled_packs.g.dart';

/// Writes [bundlePath] from every pack under `packs/`, so packages that
/// depend on ujumbe can load the packs without file access.
///
///     dart run tool/bundle_packs.dart          # regenerate
///     dart run tool/bundle_packs.dart --check  # fail if it is out of date
void main(List<String> args) {
  final check = args.contains('--check');
  final unknown = args.where((a) => a != '--check');
  if (unknown.isNotEmpty) {
    stderr.writeln('Usage: dart run tool/bundle_packs.dart [--check]');
    exitCode = 64;
    return;
  }

  final String source;
  try {
    source = renderBundle(packDirectories(Directory('packs')));
  } on Exception catch (e) {
    stderr.writeln(e);
    exitCode = 1;
    return;
  }

  final file = File(bundlePath);
  if (check) {
    final current = file.existsSync() ? file.readAsStringSync() : null;
    if (current != source) {
      stderr.writeln(
        '$bundlePath is out of date. Run: dart run tool/bundle_packs.dart',
      );
      exitCode = 1;
    } else {
      stdout.writeln('$bundlePath is up to date.');
    }
    return;
  }
  file.writeAsStringSync(source);
  stdout.writeln('Wrote $bundlePath.');
}

/// Renders the Dart index for the packs in [dirs]. Each pack is validated
/// first and embedded byte for byte, so a signature over `pack.yaml` also
/// verifies the bundled copy.
String renderBundle(List<Directory> dirs) {
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/bundle_packs.dart from packs/*/pack.yaml and '
      'statement.yaml.',
    )
    ..writeln(
      '// Do not edit. Regenerate with: dart run tool/bundle_packs.dart',
    )
    ..writeln()
    ..writeln('/// The YAML source of every pack in `packs/`, by pack id.')
    ..writeln('const bundledPackSources = <String, String>{');
  for (final dir in dirs) {
    final loaded = PackDirectory.load(dir);
    final yaml = File('${dir.path}/pack.yaml').readAsStringSync();
    if (yaml.contains("'''")) {
      throw FormatException('${dir.path}/pack.yaml must not contain \'\'\'');
    }
    out
      ..writeln("  '${loaded.pack.id}': r'''")
      ..write(yaml)
      ..writeln("''',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// The YAML source of every statement pack in '
      '`packs/*/statement.yaml`, by id.',
    )
    ..writeln('const bundledStatementPackSources = <String, String>{');
  for (final dir in dirs) {
    final loaded = PackDirectory.load(dir);
    final statement = loaded.statementPack;
    if (statement == null) continue;
    final yaml = File('${dir.path}/statement.yaml').readAsStringSync();
    if (yaml.contains("'''")) {
      throw FormatException(
        '${dir.path}/statement.yaml must not contain \'\'\'',
      );
    }
    out
      ..writeln("  '${statement.id}': r'''")
      ..write(yaml)
      ..writeln("''',");
  }
  out.writeln('};');
  return out.toString();
}
